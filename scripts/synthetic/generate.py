def _fake_user_profile(
    rng: _Rng, context: _CaseContext, is_narrow: bool
) -> tuple[dict[str, object], dict[str, object]]:
    result = {
        "user": context.user,
        "department": rng.pick(_DEPARTMENTS),
        "account_enabled": True,
        "privileged": rng.chance(0.1),
        "manager": f"user{rng.below(10_000):04d}@example.com",
    }
