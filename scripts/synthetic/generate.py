class Scenario(_Strict):
    seed: int
    first_monday: date
    weeks: int = Field(ge=1)
    # Where `--scenario NAME` writes; fixture scenarios have none, their folder is registered.
    output_dir: Path | None = None
    # Where `--update-golden` writes the golden file; without it, next to the data.
    golden_dir: Path | None = None
    has_readme: bool = False
    agent: AgentSpec
    versions: tuple[VersionSpec, ...]
    traces: TraceLayout
    noise: Noise
    agent_accuracy: Accuracy
    classes: tuple[ClassSpec, ...]
    behaviors: tuple[Behavior, ...] = ()
    sub_agent: SubAgentSpec | None = None
    analyst_labels: dict[Verdict, tuple[str, ...]]
    agent_labels: dict[Verdict, str]
    config: dict[str, Any]
    checklists: tuple[dict[str, Any], ...]


def load_scenario(name: str) -> Scenario:
    return Scenario.model_validate(
        load_yaml12(SCENARIO_DIR / f"{name}.yaml", max_bytes=1 << 20, what="scenarios are small")
    )


def generate(scenario: Scenario, out_dir: Path) -> list[Path]:
    """Write every file of the scenario into `out_dir`; return the written paths, sorted."""
    unknown = {tool for spec in scenario.classes for tool in spec.tools} - _TOOLS.keys()
    if unknown:
        raise ValueError(f"the scenario names tools the generator cannot fake: {sorted(unknown)}")
    cases = make_cases(scenario)
    written = [
        *write_traces(scenario, cases, out_dir / "traces"),
        write_verdicts(cases, out_dir / "verdicts.csv"),
        *write_checklists(scenario, out_dir / "checklists"),
        _write_config(scenario, out_dir / "detecttrace.yaml"),
    ]
    if scenario.has_readme:
        written.append(write_text(out_dir / "README.txt", README_TEXT))
    return sorted(written, key=lambda path: path.as_posix())


def update_golden(out_dir: Path, golden_dir: Path) -> list[Path]:
    """Run the check on `out_dir` and write its results and dashboard into `golden_dir`, version
    normalized."""
    # Imported here so generating data never depends on the pipeline being importable.
    from detecttrace.dashboard import render_dashboard
    from detecttrace.pipeline import run_check
    from detecttrace.runconfig import load_run_config

    config_path = out_dir / "detecttrace.yaml"
    results = run_check(load_run_config(config_path), config_path).results
    return [
        write_text(golden_dir / GOLDEN_NAME, to_golden_text(normalize_results(results))),
        write_text(golden_dir / GOLDEN_HTML_NAME, normalize_dashboard(render_dashboard(results))),
        write_text(golden_dir / VIEW_GOLDEN_NAME, to_view_golden_text(results)),
    ]


def to_golden_dir(scenario: Scenario, out_dir: Path) -> Path:
    return REPO_ROOT / scenario.golden_dir if scenario.golden_dir else out_dir


def normalize_results(results: dict[str, object]) -> dict[str, object]:
    """Drop what changes with every release, so the golden file changes only with the numbers."""
    return {**results, "generated_by": "detecttrace"}


def normalize_dashboard(html: str) -> str:
    """Keep only the template's own markup: drop the version from the generator marker and
    the footer, and put placeholders in place of the stylesheet, the script, the results block
    and the two policy hashes. Those parts have tests of their own, and a golden full of them
    would change with every stylesheet or script edit and hide the markup changes."""
    from detecttrace.dashboard import GENERATOR_PREFIX

    text = html.replace(f"{GENERATOR_PREFIX} {__version__}", GENERATOR_PREFIX)
    for pattern, replacement in _DASHBOARD_PLACEHOLDERS:
        text = pattern.sub(replacement, text, count=1)
    return text


def to_golden_text(results: object) -> str:
    return json.dumps(results, ensure_ascii=False, allow_nan=False, indent=1) + "\n"


def to_view_golden_text(results: Mapping[str, object]) -> str:
    """The dashboard view model as the React tests read it, its field order kept."""
    from detecttrace.dashboard_view import build_view, to_view_json

    view = to_view_json(build_view(results))
    return json.dumps(view, ensure_ascii=False, allow_nan=False, indent=2) + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate synthetic DetectTrace datasets.")
    parser.add_argument("--scenario", help="write only this scenario (a name in scenarios/)")
    parser.add_argument("--out", type=Path, help="output folder (default: the scenario's)")
    parser.add_argument(
        "--update-golden",
        action="store_true",
        help=f"also rewrite {GOLDEN_NAME}, {GOLDEN_HTML_NAME} and {INIT_GOLDEN_NAME}",
    )
    args = parser.parse_args(argv)
    if args.scenario is None:
        if args.out is not None:
            parser.error("--out needs --scenario")
        paths = _write_everything(args.update_golden)
    else:
        scenario = load_scenario(args.scenario)
        if args.out is None and scenario.output_dir is None:
            parser.error(f"scenario {args.scenario} has no output_dir; give --out")
        out_dir: Path = args.out or REPO_ROOT / (scenario.output_dir or "")
        paths = generate(scenario, out_dir)
        if args.update_golden:
            paths.extend(update_golden(out_dir, to_golden_dir(scenario, out_dir)))
    for path in paths:
        print(path)
    return 0


def _write_everything(should_update_golden: bool) -> list[Path]:
    # Imported here because fixture_specs builds on this module.
    import fixture_specs

    scenario = load_scenario("demo")
    demo_dir = REPO_ROOT / (scenario.output_dir or "")
    paths = generate(scenario, demo_dir)
    if should_update_golden:
        paths.extend(update_golden(demo_dir, to_golden_dir(scenario, demo_dir)))
    for spec in fixture_specs.FIXTURES:
        paths.extend(fixture_specs.write_fixture(spec, fixture_specs.FIXTURE_ROOT))
        if should_update_golden:
            paths.append(fixture_specs.update_fixture_golden(spec, fixture_specs.FIXTURE_ROOT))
            if spec.name in fixture_specs.INIT_VARIANTS:
                paths.append(fixture_specs.update_init_golden(spec, fixture_specs.FIXTURE_ROOT))
            if spec.name in fixture_specs.VIEW_FIXTURES:
                paths.append(fixture_specs.update_view_golden(spec, fixture_specs.FIXTURE_ROOT))
    return paths


class _Rng:
    """The only source of randomness: every draw goes through `random.Random.random()`."""

    def __init__(self, seed: int, part: str) -> None:
        # One stream per part (a class's schedule, one case), so tuning one case's
        # behavior leaves every other case unchanged.
        digest = hashlib.sha256(f"{seed}/{part}".encode()).digest()
        self._random = random.Random(int.from_bytes(digest[:8], "big"))

    def chance(self, probability: float) -> bool:
        return self._random.random() < probability

    def below(self, limit: int) -> int:
        return min(int(self._random.random() * limit), limit - 1)

    def between(self, low: int, high: int) -> int:
        return low + self.below(high - low + 1)

    def pick(self, options: Sequence[Any]) -> Any:
        return options[self.below(len(options))]

    def hex(self, digits: int) -> str:
        return "".join(f"{self.below(1 << 16):04x}" for _ in range(digits // 4))

    def ip(self) -> str:
        return f"{self.pick(_DOC_NETWORKS)}.{self.between(1, 254)}"

    def asn(self) -> int:
        return self.between(_DOC_AS_FIRST, _DOC_AS_LAST)


@dataclass(slots=True)
class _CaseContext:
    alert_class: str
    user: str
    usual_ip: str
    alert_ip: str
    app_id: str
    app_name: str
    is_threat: bool
    alert_ns: int


@dataclass(slots=True)
class _Call:
    tool: str
    is_narrow: bool
    is_failed: bool
    in_sub_agent: bool


@dataclass(slots=True)
class _Case:
    case_id: str
    alert_class: str
    week: int
    version: str
    analyst: Verdict
    analyst_label: str
    agent: Verdict
    start_ns: int
    closed_ns: int = 0
    end_ns: int = 0
    spans: list[dict[str, Any]] = field(default_factory=list)


def make_cases(scenario: Scenario) -> list[_Case]:
    monday = datetime.combine(scenario.first_monday, datetime.min.time(), tzinfo=UTC)
    first_ns = int(monday.timestamp()) * _NS
    cases: list[_Case] = []
    for spec in scenario.classes:
        rng = _Rng(scenario.seed, spec.name)
        # Drawn per class and week first, so numbering follows time within a class.
        starts = sorted(
            (week, first_ns + ((week - 1) * _WEEK_SECONDS + rng.below(_WEEK_SECONDS)) * _NS)
            for week in range(1, scenario.weeks + 1)
            for _ in range(spec.cases_per_week + rng.between(-3, 3))
        )
        sub_agent_week = (
            scenario.sub_agent.week
            if scenario.sub_agent and scenario.sub_agent.class_ == spec.name
            else None
        )
        for number, (week, start_ns) in enumerate(starts, start=1):
            has_sub_agent = week == sub_agent_week
            if has_sub_agent:
                sub_agent_week = None
            cases.append(
                _make_case(
                    _Rng(scenario.seed, f"{spec.case_prefix}-{number:04d}"),
                    scenario,
                    spec,
                    f"{spec.case_prefix}-{number:04d}",
                    week,
                    start_ns,
                    has_sub_agent,
                )
            )
    return sorted(cases, key=lambda case: (case.start_ns, case.case_id))


def _make_case(
    rng: _Rng,
    scenario: Scenario,
    spec: ClassSpec,
    case_id: str,
    week: int,
    start_ns: int,
    has_sub_agent: bool,
) -> _Case:
    version = max(
        (version for version in scenario.versions if version.first_week <= week),
        key=lambda version: version.first_week,
    ).name
    analyst = _draw_analyst(rng, spec)
    labels = scenario.analyst_labels[analyst]
    analyst_label = labels[0] if len(labels) == 1 or rng.chance(0.8) else rng.pick(labels[1:])
    behaviors = [b for b in scenario.behaviors if b.class_ == spec.name and b.version == version]
    sub_tools = scenario.sub_agent.tools if has_sub_agent and scenario.sub_agent else ()
    calls = _plan_calls(rng, scenario.noise, spec.tools, behaviors, sub_tools)
    agent = _draw_agent(rng, scenario.agent_accuracy, analyst, calls, behaviors)
    case = _Case(case_id, spec.name, week, version, analyst, analyst_label, agent, start_ns)
    context = _CaseContext(
        alert_class=spec.name,
        user=f"user{rng.below(10_000):04d}@example.com",
        usual_ip=rng.ip(),
        alert_ip=rng.ip(),
        app_id=_uuid(rng),
        app_name=rng.pick(_APP_NAMES),
        is_threat=analyst == "true_positive",
        alert_ns=start_ns - rng.between(60, 900) * _NS,
    )
    _build_spans(rng, scenario, case, context, calls)
    case.closed_ns = case.end_ns + rng.between(20, 36 * 60) * 60 * _NS
    return case


def _draw_analyst(rng: _Rng, spec: ClassSpec) -> Verdict:
    if rng.chance(spec.true_positive_rate):
        return "true_positive"
    return "false_positive" if rng.chance(spec.false_positive_share) else "benign"


def _plan_calls(
    rng: _Rng,
    noise: Noise,
    tools: Sequence[str],
    behaviors: Sequence[Behavior],
    sub_tools: Sequence[str],
) -> list[_Call]:
    calls: list[_Call] = []
    for tool in tools:
        skip = max((b.skip for b in behaviors if b.tool == tool), default=0.0)
        narrow = max((b.narrow for b in behaviors if b.tool == tool), default=0.0)
        if rng.chance(noise.skip) or rng.chance(skip):
            continue
        is_narrow = rng.chance(noise.narrow) or rng.chance(narrow)
        in_sub_agent = tool in sub_tools
        if rng.chance(noise.failure):
            calls.append(_Call(tool, is_narrow, True, in_sub_agent))
            if not rng.chance(noise.retry):
                continue
        calls.append(_Call(tool, is_narrow, False, in_sub_agent))
    return calls


def _draw_agent(
    rng: _Rng,
    accuracy: Accuracy,
    analyst: Verdict,
    calls: Sequence[_Call],
    behaviors: Sequence[Behavior],
) -> Verdict:
    succeeded = {call.tool for call in calls if not call.is_failed}
    if analyst == "true_positive":
        for behavior in behaviors:
            if behavior.tool not in succeeded and rng.chance(behavior.missed_threat_close):
                return "benign"
        if rng.chance(accuracy.threat):
            return "true_positive"
        return "false_positive"
    if rng.chance(accuracy.non_threat):
        return analyst
    if rng.chance(0.15):
        return "true_positive"
    return "benign" if analyst == "false_positive" else "false_positive"


def _build_spans(
    rng: _Rng, scenario: Scenario, case: _Case, context: _CaseContext, calls: Sequence[_Call]
) -> None:
    trace_id = rng.hex(32)
    root_id = rng.hex(16)
    clock = [case.start_ns + rng.between(2, 9) * _MS]

    def chat(parent_id: str) -> None:
        start = clock[0]
        clock[0] += rng.between(600, 2800) * _MS
        attributes = {
            conventions.OPERATION_ATTRIBUTE: _CHAT,
            _PROVIDER: "example",
            _REQUEST_MODEL: scenario.agent.model,
            _INPUT_TOKENS: rng.between(900, 6000),
            _OUTPUT_TOKENS: rng.between(40, 600),
        }
        name = f"{_CHAT} {scenario.agent.model}"
        case.spans.append(
            _span(trace_id, rng.hex(16), parent_id, name, _KIND_CLIENT, start, clock[0], attributes)
        )
        clock[0] += rng.between(1, 6) * _MS

    def tool(call: _Call, parent_id: str) -> None:
        arguments, result = _TOOLS[call.tool](rng, context, call.is_narrow)
        start = clock[0]
        clock[0] += rng.between(120, 1900) * _MS
        attributes: dict[str, object] = {
            conventions.OPERATION_ATTRIBUTE: conventions.EXECUTE_TOOL,
            conventions.TOOL_NAME: call.tool,
            _TOOL_TYPE: "function",
            _TOOL_CALL_ID: f"call_{rng.hex(24)}",
            conventions.TOOL_CALL_ARGUMENTS: json.dumps(arguments),
        }
        status: dict[str, object] = {}
        if call.is_failed:
            attributes[conventions.ERROR_TYPE] = "timeout"
            status = {"code": _STATUS_ERROR, "message": "upstream request timed out"}
        else:
            attributes[conventions.TOOL_CALL_RESULT] = json.dumps(result)
        name = f"{conventions.EXECUTE_TOOL} {call.tool}"
        case.spans.append(
            _span(
                trace_id,
                rng.hex(16),
                parent_id,
                name,
                _KIND_INTERNAL,
                start,
                clock[0],
                attributes,
                status,
            )
        )
        clock[0] += rng.between(1, 6) * _MS

    chat(root_id)
    main_calls = [call for call in calls if not call.in_sub_agent]
    for index, call in enumerate(main_calls):
        tool(call, root_id)
        if index % 2 == 1:
            chat(root_id)
    sub_calls = [call for call in calls if call.in_sub_agent]
    if sub_calls and scenario.sub_agent:
        sub_id = rng.hex(16)
        sub_start = clock[0]
        chat(sub_id)
        for call in sub_calls:
            tool(call, sub_id)
        chat(sub_id)
        attributes = {
            conventions.OPERATION_ATTRIBUTE: conventions.INVOKE_AGENT,
            _AGENT_NAME: scenario.sub_agent.name,
            _REQUEST_MODEL: scenario.agent.model,
        }
        name = f"{conventions.INVOKE_AGENT} {scenario.sub_agent.name}"
        case.spans.append(
            _span(trace_id, sub_id, root_id, name, _KIND_INTERNAL, sub_start, clock[0], attributes)
        )
    chat(root_id)
    case.end_ns = clock[0] + rng.between(2, 9) * _MS
    attributes = {
        conventions.OPERATION_ATTRIBUTE: conventions.INVOKE_AGENT,
        _AGENT_NAME: scenario.agent.name,
        _REQUEST_MODEL: scenario.agent.model,
        "detecttrace.case_id": case.case_id,
        "detecttrace.alert_class": case.alert_class,
        "detecttrace.verdict": scenario.agent_labels[case.agent],
        "detecttrace.prompt_version": case.version,
    }
    name = f"{conventions.INVOKE_AGENT} {scenario.agent.name}"
    case.spans.append(
        _span(trace_id, root_id, None, name, _KIND_INTERNAL, case.start_ns, case.end_ns, attributes)
    )


def _span(
    trace_id: str,
    span_id: str,
    parent_id: str | None,
    name: str,
    kind: int,
    start_ns: int,
    end_ns: int,
    attributes: Mapping[str, object],
    status: dict[str, object] | None = None,
) -> dict[str, Any]:
    return {
        "traceId": trace_id,
        "spanId": span_id,
        "parentSpanId": parent_id or "",
        "flags": 1,
        "name": name,
        "kind": kind,
        "startTimeUnixNano": str(start_ns),
        "endTimeUnixNano": str(end_ns),
        "attributes": [_to_key_value(key, value) for key, value in attributes.items()],
        "status": status or {},
    }


def _to_key_value(key: str, value: object) -> dict[str, object]:
    if isinstance(value, bool):
        return {"key": key, "value": {"boolValue": value}}
    if isinstance(value, int):
        # OTLP JSON writes 64-bit integers as strings.
        return {"key": key, "value": {"intValue": str(value)}}
    return {"key": key, "value": {"stringValue": str(value)}}


def _uuid(rng: _Rng) -> str:
    text = rng.hex(32)
    return f"{text[:8]}-{text[8:12]}-{text[12:16]}-{text[16:20]}-{text[20:]}"


def _iso(ns: int) -> str:
    return datetime.fromtimestamp(ns // _NS, tz=UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


