class _Strict(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")


class AgentSpec(_Strict):
    name: str
    service_version: str
    model: str


class VersionSpec(_Strict):
    name: str
    first_week: int = Field(ge=1)


class TraceLayout(_Strict):
    files: int = Field(ge=1)
    cases_per_batch: int = Field(ge=1)


class Noise(_Strict):
    skip: float
    narrow: float
    failure: float
    retry: float


class Accuracy(_Strict):
    threat: float
    non_threat: float


class ClassSpec(_Strict):
    name: str
    case_prefix: str
    cases_per_week: int = Field(ge=1)
    true_positive_rate: float
    false_positive_share: float
    tools: tuple[str, ...]


class Behavior(_Strict):
    class_: str = Field(alias="class")
